"""Regenerate the bundled synthetic offline trace.

``sample_trace.json`` is generated data, not a recording of a live run. This
script derives every input-side number from the real English fixtures in
``agent.py`` using the same four message-building strategies the benchmark
uses, so the offline tables stay consistent with the prompts that are actually
shipped. Output-side numbers (completion tokens, latency) are fixed synthetic
constants, because inventing per-call generation variance would be fabricating
measurements.

Run it after changing the system prompt, tool fixtures, or summaries:

    python make_sample_trace.py
"""

import json
import os

import agent
from config import Pricing
from tracer import Tracer

TRACE_PATH = os.path.join(os.path.dirname(__file__), "sample_trace.json")

# The trace is priced with the gpt-4o-mini preset; offline mode re-prices it.
TRACE_MODEL = "gpt-4o-mini"
TRACE_PRICING = Pricing(0.15, 0.075, 0.60)

# Chat-format overhead per message plus the trailing assistant priming tokens.
_TOKENS_PER_MESSAGE = 4
_TOKENS_PER_REQUEST = 3

# Providers report cache hits in fixed-size blocks and only above a minimum.
_CACHE_BLOCK_TOKENS = 128

# Fixed synthetic output side. Identical across scenarios so the A/B comparison
# isolates input-token effects rather than generation noise.
COMPLETION_TOKENS = [104, 112, 136, 148, 127, 155, 141, 130]
LATENCY_S = 2.5


def _assistant_placeholder(idx: int, tool: str) -> str:
    """Deterministic stand-in for the model's reply after turn ``idx``."""
    return (f"[Assistant turn {idx + 1}] Reviewed the {tool} result, confirmed it "
            "against policy, and selected the next action for this refund case.")


def _prompt_tokens(messages) -> int:
    return sum(_TOKENS_PER_MESSAGE + agent._ntok(m["content"]) for m in messages) \
        + _TOKENS_PER_REQUEST


def _common_prefix_tokens(prev, cur) -> int:
    """Token length of the leading messages that two requests share verbatim."""
    total = 0
    for a, b in zip(prev, cur):
        if a["role"] != b["role"] or a["content"] != b["content"]:
            break
        total += _TOKENS_PER_MESSAGE + agent._ntok(a["content"])
    return total


def _cached_tokens(prefix_tokens: int, prompt_tokens: int) -> int:
    """Model a provider cache: block-aligned, and only above the minimum size."""
    if prefix_tokens < agent.MIN_CACHEABLE_PREFIX_TOKENS:
        return 0
    cached = prefix_tokens // _CACHE_BLOCK_TOKENS * _CACHE_BLOCK_TOKENS
    return min(cached, prompt_tokens)


def build_scenario(key: str) -> dict:
    """Replay one 2x2 cell offline and return its trace entry."""
    name, kv_cache, compress = agent.SCENARIOS[key]

    turns, records, prev_messages = [], [], None
    for idx, (step, tool, result) in enumerate(agent.TOOL_RESULTS):
        messages, tool_ctx = agent.build_messages(
            idx, step, tool, result, turns, kv_cache, compress)
        prompt_tokens = _prompt_tokens(messages)

        if not kv_cache:
            # A volatile per-request header makes the very first token differ,
            # so no prefix is ever reusable.
            cached = 0
        elif prev_messages is None:
            # Live runs warm the stable prefix first, so turn 1 already hits.
            cached = _cached_tokens(
                _common_prefix_tokens(messages, messages), prompt_tokens)
        else:
            cached = _cached_tokens(
                _common_prefix_tokens(prev_messages, messages), prompt_tokens)

        records.append({
            "step": step,
            "tool": tool,
            "kind": "llm",
            "prompt_tokens": prompt_tokens,
            "cached_tokens": cached,
            "completion_tokens": COMPLETION_TOKENS[idx],
            "tool_ctx_tokens": tool_ctx,
            "latency_s": LATENCY_S,
        })
        prev_messages = messages
        turns.append((step, _assistant_placeholder(idx, tool), tool, result))

    tr = Tracer.from_records(records, name=name, pricing=TRACE_PRICING)
    return {
        "key": key,
        "name": name,
        "total_cost": tr.total_cost(),
        "component_costs": tr.component_costs(),
        "cost_distribution": tr.cost_distribution(),
        "spans": tr.to_records(),
    }


def build_trace() -> dict:
    agent.validate_benchmark()
    return {
        "model": TRACE_MODEL,
        "provenance": "synthetic",
        "language": "en",
        "note": ("Generated by make_sample_trace.py from the English fixtures in "
                 "agent.py. Input-side counts are tokenizer-derived; completion "
                 "tokens and latency are fixed synthetic constants. These are not "
                 "measurements of a live model run."),
        "pricing": {
            "input": TRACE_PRICING.input_per_m,
            "cached": TRACE_PRICING.cached_per_m,
            "output": TRACE_PRICING.output_per_m,
        },
        "scenarios": [build_scenario(k) for k in ("naive", "kv", "compress", "both")],
    }


def main() -> None:
    with open(TRACE_PATH, "w", encoding="utf-8") as f:
        json.dump(build_trace(), f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"Wrote synthetic trace to {TRACE_PATH}")


if __name__ == "__main__":
    main()
